// Generates src/calendars/umalqura-table.ts from ICU's islamic-umalqura calendar (ADR-0006).
// Runtime code never calls Intl calendars; this script runs at development time only.
//
//   node scripts/generate-umalqura.mjs          write the table
//   node scripts/generate-umalqura.mjs --check  fail if the committed table's data differs
import { readFileSync, writeFileSync } from 'node:fs';

const FIRST_YEAR = 1300;
const LAST_YEAR = 1500; // ICU's table is official to 1500 AH; later years are extrapolated.
const UNIX_EPOCH_JDN = 2_440_588;
const OUT = new URL('../src/calendars/umalqura-table.ts', import.meta.url);

const fmt = new Intl.DateTimeFormat('en-u-ca-islamic-umalqura', {
  timeZone: 'UTC',
  year: 'numeric',
  month: 'numeric',
  day: 'numeric',
});
if (fmt.resolvedOptions().calendar !== 'islamic-umalqura') {
  throw new Error('This Node build lacks ICU islamic-umalqura; use a full-ICU Node.');
}

function hijriOf(jdn) {
  const parts = fmt.formatToParts(new Date((jdn - UNIX_EPOCH_JDN) * 86_400_000));
  const get = (t) => Number(parts.find((p) => p.type === t)?.value);
  return { year: get('year'), month: get('month'), day: get('day') };
}

// Find 1 Muharram FIRST_YEAR, starting from a day known to be shortly before it (Nov 1882).
let jdn = 2_408_380;
while (!(hijriOf(jdn).year === FIRST_YEAR && hijriOf(jdn).day === 1)) jdn++;
const startJdn = jdn;

// Walk month by month, recording each month's length.
const years = [];
for (let year = FIRST_YEAR; year <= LAST_YEAR; year++) {
  let bits = 0;
  for (let month = 1; month <= 12; month++) {
    const start = hijriOf(jdn);
    if (start.year !== year || start.month !== month || start.day !== 1) {
      throw new Error(`Expected 1/${month}/${year} at JDN ${jdn}, got ${JSON.stringify(start)}`);
    }
    const length = hijriOf(jdn + 29).day === 30 ? 30 : 29;
    if (length === 30) bits |= 1 << (month - 1);
    jdn += length;
  }
  years.push(bits.toString(16).padStart(3, '0'));
}

const lines = [];
for (let i = 0; i < years.length; i += 20) {
  lines.push(`  '${years.slice(i, i + 20).join('')}'`);
}
const data = `export const UMALQURA_FIRST_YEAR = ${FIRST_YEAR};
export const UMALQURA_LAST_YEAR = ${LAST_YEAR};

/** JDN of 1 Muharram ${FIRST_YEAR} AH. */
export const UMALQURA_START_JDN = ${startJdn};

/**
 * Month lengths, three hex digits per year from ${FIRST_YEAR} AH. Each is a 12-bit mask:
 * bit 0 = Muharram … bit 11 = Dhu al-Hijjah; 1 = 30 days, 0 = 29 days.
 */
export const UMALQURA_MONTH_LENGTHS =
${lines.join(' +\n')};
`;
const header = `// Generated by scripts/generate-umalqura.mjs from ICU ${process.versions.icu} islamic-umalqura. Do not edit.\n\n`;

const dataOf = (text) => text.slice(text.indexOf('export const'));
if (process.argv.includes('--check')) {
  const committed = readFileSync(OUT, 'utf8');
  if (dataOf(committed) !== data) {
    console.error(
      `umalqura-table.ts differs from ICU ${process.versions.icu}. Regenerate it and review the change.`,
    );
    process.exit(1);
  }
  console.log(`umalqura-table.ts matches ICU ${process.versions.icu} (${years.length} years).`);
} else {
  writeFileSync(OUT, header + data);
  console.log(
    `Wrote ${years.length} years (${FIRST_YEAR}–${LAST_YEAR} AH), start JDN ${startJdn}.`,
  );
}
